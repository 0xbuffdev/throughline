import type { CompiledTrace, SourceIds, ViewDescriptor, ViewItem } from "../../v2/model.js";
import { sequenceActors, type SequenceActor } from "../../v2/sequence-layout.js";

/** Internal Mermaid input and the source identities it presents. */
export type ProofElement = Readonly<{
	id: string;
	itemId: string;
	role: ViewItem["role"];
	label: string;
	description: string;
	source: SourceIds;
	current: boolean;
	context?: boolean;
	visited?: boolean;
	strokeToken?: string;
	/** Host-authored sequence row reference, not a semantic event ID. */
	rowToken?: string;
	sent?: boolean;
	flowLabel?: string;
	fromItemId?: string;
	toItemId?: string;
	collapsed?: boolean;
}>;
export type DiagramProof = Readonly<{
	kind: "graph" | "sequence";
	source: string;
	elements: readonly ProofElement[];
	visibleEvents: number;
	totalEvents: number;
	start: number;
	diagnostics: readonly string[];
}>;
const participants = new WeakMap<CompiledTrace, readonly SequenceActor[]>();

export function property(item: ViewItem, key: string): unknown {
	return item.data && typeof item.data === "object" && !Array.isArray(item.data)
		? item.data[key] : undefined;
}

// Separate grammar contexts share numeric entity escaping, not JSON quoting.
// Never emit a label as syntax, a directive, HTML, a URL, or a CSS declaration.
const plainLabelCharacter = /[\p{L}\p{N} _.-]/u;

export function label(text: string): string {
	return [...text].slice(0, 80).map(char => plainLabelCharacter.test(char)
		? char : /\s/u.test(char) ? " " : "#" + char.codePointAt(0) + ";").join("");
}

// Sequence's automatic word wrapping can split Mermaid's internal entity
// escapes. Wrap plain text first, then escape it. Only this fixed line-break
// markup is generated by the trusted adapter, never supplied by the author.
function wrappedLabel(text: string, lineLength: number, maxLines: number,
	accountForEscapes = false): string {
	// Mermaid measures the encoded numeric entity before replacing it with
	// its glyph. Allow room for that token as well as the printed character.
	const weight = (char: string) => !accountForEscapes || plainLabelCharacter.test(char)
		? 1 : 5 + String(char.codePointAt(0)).length;
	const length = (line: string) => [...line].reduce((sum, char) => sum + weight(char), 0);
	const words = [...text].slice(0, 80).join("").split(/\s+/).flatMap(word => {
		const chunks: string[] = [];
		let chunk = "";
		for (const char of word) {
			if (chunk && length(chunk) + weight(char) > lineLength) {
				chunks.push(chunk);
				chunk = "";
			}
			chunk += char;
		}
		if (chunk) chunks.push(chunk);
		return chunks;
	});
	const lines: string[] = [];
	let line = "";
	for (const word of words) {
		if (line && length(line + " " + word) > lineLength) { lines.push(line); line = ""; }
		line += (line ? " " : "") + word;
	}
	if (line) lines.push(line);
	const visible = lines.slice(0, maxLines);
	if (lines.length > maxLines) {
		const last = [...visible[maxLines - 1]];
		while (last.length && length(last.join("") + "...") > lineLength) last.pop();
		visible[maxLines - 1] = last.join("") + "...";
	}
	return visible.map(label).join("<br/>");
}

function element(item: ViewItem, index = 0): ProofElement {
	if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(item.id))
		throw new Error("Unsupported generated view identity");
	return Object.freeze({
		id: "thl_" + item.id, itemId: item.id, role: item.role,
		label: item.label, description: item.description, source: item.source,
		current: property(item, "current") === true || Number(property(item, "sentCurrent")) > 0,
		fromItemId: item.fromItemId,
		toItemId: item.toItemId,
		...(item.role === "group" ? { collapsed: property(item, "collapsed") === true } : {}),
		...(item.role === "relation" ? {
			strokeToken: "#" + (0x100000 + index).toString(16),
			context: Number(property(item, "observedCurrent")) > 0,
		} : {}),
		...(item.role === "event" ? { sent: property(item, "phase") === "sent" } : {}),
	});
}

function result(kind: DiagramProof["kind"], lines: string[], elements: ProofElement[],
	visibleEvents = 0, totalEvents = 0, start = 0, diagnostics: string[] = []): DiagramProof {
	return Object.freeze({ kind, source: lines.join("\n"), elements: Object.freeze(elements),
		visibleEvents, totalEvents, start, diagnostics: Object.freeze(diagnostics) });
}

export function graphProof(trace: CompiledTrace, view: ViewDescriptor,
	direction: "LR" | "TB" = "LR", visitedRelations?: ReadonlySet<string>): DiagramProof {
	if (view.kind !== "graph") throw new Error("Graph descriptor required");
	const visible = view.items.filter(item => ["entity", "group", "relation"].includes(item.role));
	if (visible.length > 1_400) throw new Error("Graph proof work limit exceeded");
	const elements = visible.map(element);
	const byItem = new Map(elements.map(item => [item.itemId, item]));
	const groups = visible.filter(item => item.role === "group");
	const groupBySource = new Map(groups.map(item => [item.source.groupIds![0], item]));
	const sourceGroups = new Map(trace.artifact.groups?.map(group => [group.id, group]));
	const entities = new Map(trace.artifact.entities.map(entity => [entity.id, entity]));
	const relations = new Map(trace.artifact.relations.map(relation => [relation.id, relation]));
	const relationLabel = (item: ViewItem) => item.source.relationIds?.length === 1
		? relations.get(item.source.relationIds[0])?.label : undefined;
	const lines = ["flowchart " + direction];
	const children = new Map<string | undefined, ViewItem[]>();
	for (const item of visible) {
		if (item.role === "relation") continue;
		const sourceGroup = item.role === "group"
			? sourceGroups.get(item.source.groupIds![0])?.parentId
			: entities.get(item.source.entityIds![0])?.groupId;
		const parent = sourceGroup ? groupBySource.get(sourceGroup)?.id : undefined;
		const list = children.get(parent) ?? [];
		list.push(item); children.set(parent, list);
	}
	function emit(parent?: string): void {
		for (const item of children.get(parent) ?? []) {
			const entry = byItem.get(item.id)!;
			if (item.role === "group" && property(item, "collapsed") !== true) {
				lines.push('subgraph ' + entry.id + '["' + wrappedLabel(item.label, 24, 3) + '"]');
				emit(item.id);
				lines.push("end");
			} else {
				lines.push(entry.id + '("' + wrappedLabel(item.label, 20, 4) + '")');
				// A host-owned class is an explicit map key, not Mermaid's private ID.
				lines.push("class " + entry.id + " " + entry.id + "_source");
			}
		}
	}
	emit();
	for (const item of visible.filter(item => item.role === "relation")) {
		const entry = byItem.get(item.id)!;
		const from = byItem.get(item.fromItemId ?? ""), to = byItem.get(item.toItemId ?? "");
		if (!from || !to) throw new Error("Relation endpoint missing from projected graph");
		// Caption the active route without making every edge reserve label space.
		lines.push(from.id + " " + entry.id + "@--> " + to.id);
		lines.push("class " + entry.id + " " + entry.id + "_source");
		// A unique trusted paint token survives documented classDef compilation.
		// The renderer binds it to this source entry without private SVG IDs.
		// No frame-dependent styling enters geometry source.
		lines.push("classDef " + entry.id + "_source stroke:" + entry.strokeToken + ",stroke-width:1.5px");
	}
	return result("graph", lines, elements.map((entry, index) => entry.role === "relation"
		? Object.freeze({ ...entry, flowLabel: relationLabel(visible[index]) ?? "",
			visited: entry.source.relationIds?.some(id => visitedRelations?.has(id)) }) : entry));
}

export function sequenceProof(trace: CompiledTrace, view: ViewDescriptor,
	requestedStart?: number, windowSize = 40): DiagramProof {
	if (view.kind !== "sequence") throw new Error("Sequence descriptor required");
	if (!Number.isSafeInteger(windowSize) || windowSize < 1 || windowSize > 120)
		throw new Error("Sequence window must contain 1–120 events");
	const relations = new Map(trace.artifact.relations.map(relation => [relation.id, relation]));
	// Reserve the complete modeled message participant set from frame zero.
	const actors = participants.get(trace) ?? sequenceActors(trace);
	participants.set(trace, actors);
	const lines = ["sequenceDiagram"];
	const actorIds = new Map<string, string>();
	const elements: ProofElement[] = [];
	for (const actor of actors) {
		const id = "thl_" + actor.itemId;
		actorIds.set(actor.entityId, id);
		lines.push("participant " + id + " as " + wrappedLabel(actor.label, 15, 3));
		elements.push(Object.freeze({ id, itemId: actor.itemId, role: "entity",
			label: actor.label, description: "Modeled message participant, not evidence of current presence.",
			source: Object.freeze({ entityIds: Object.freeze([actor.entityId]) }), current: false }));
	}
	const events = view.items.filter(item => item.role === "event" && property(item, "type") === "message");
	const lastStart = Math.max(0, events.length - windowSize);
	const start = requestedStart === undefined ? lastStart : Math.min(lastStart,
		Math.max(0, Number.isSafeInteger(requestedStart) ? requestedStart : 0));
	const window = events.slice(start, start + windowSize);
	const followupIds = new Set(window.filter(item => property(item, "current") === true &&
		property(item, "phase") !== "sent" && property(item, "missingSentThroughStep") === false)
		.map(item => property(item, "messageId")));
	const rows = window.map(item => {
		const entry = element(item);
		const from = actorIds.get(String(property(item, "fromEntityId")));
		const to = actorIds.get(String(property(item, "toEntityId")));
		if (!from || !to) throw new Error("Message endpoints missing from projected sequence");
		const phase = property(item, "phase");
		const relation = relations.get(item.source.relationIds![0])!;
		const messageId = String(property(item, "messageId"));
		const flowLabel = relation.label ?? messageId;
		// Mermaid expands lanes for long adjacent messages. Bound their labels
		// independently of the participant labels and retain the full captions
		// in source inspection. The arrow already encodes the sent phase.
		const caption = phase === "sent" ? wrappedLabel(flowLabel, 12, 4, true)
			: label(String(phase)) + "<br/>" + wrappedLabel(messageId, 16, 1, true);
		return { item, entry, from, to, phase, flowLabel, messageId, caption };
	});
	// Reserve every reference-shaped string in the rendered compact captions.
	// The no-whitespace form conservatively covers SVG textContent joining
	// adjacent lines. Numeric escapes cannot emit ASCII letters/digits (those
	// are emitted literally); decode them once to cover punctuation too.
	const reserved = new Set<string>();
	for (const { caption } of rows) {
		const text = caption.replaceAll("<br/>", "").replace(/#(\d+);/g, (_, n: string) => String.fromCodePoint(Number(n)));
		for (const token of text.replace(/\s/g, "").match(/TL\d{6}/g) ?? []) reserved.add(token);
	}
	const nominal = new Set(rows.map(({ item }) => "TL" + item.id.slice("event_".length).padStart(6, "0")));
	let alternate = 10_000;
	for (const { item, entry, from, to, phase, flowLabel, messageId, caption } of rows) {
		// Fixed-width, deterministic references are scoped to this window.
		// Keep ordinary projected indices unless an authored caption collides;
		// select an unused reference without changing authored text or identity.
		let rowToken = "TL" + item.id.slice("event_".length).padStart(6, "0");
		if (!/^TL\d{6}$/.test(rowToken)) throw new Error("Unsupported sequence row identity");
		if (reserved.has(rowToken)) {
			do { rowToken = "TL" + String(alternate++).padStart(6, "0"); }
			while (reserved.has(rowToken) || nominal.has(rowToken));
			if (!/^TL\d{6}$/.test(rowToken)) throw new Error("Sequence row reference space exhausted");
		}
		reserved.add(rowToken);
		const tagged = caption + "<br/>" + rowToken;
		lines.push("%% " + entry.id);
		if (phase === "sent") lines.push(from + "-)" + to + ": " + tagged);
		else lines.push("Note over " + (from === to ? to : from + "," + to) + ": " + tagged);
		elements.push(Object.freeze({ ...entry, rowToken, flowLabel, visited: !entry.current,
			context: entry.sent && !entry.current && followupIds.has(property(item, "messageId")) }));
	}
	return result("sequence", lines, elements, window.length, events.length, start,
		events.length > window.length ? ["Showing " + window.length + " of " +
			events.length + " recorded message phases. Full history is in Changes and evidence."] : []);
}
