import type { CompiledTrace, SourceIds, ViewDescriptor, ViewItem } from "../../../v2/model.js";

/** TL-U26 experiment only. Not a package export or an alternate trace model. */
export type ProofElement = Readonly<{
	id: string;
	itemId: string;
	role: ViewItem["role"];
	label: string;
	description: string;
	source: SourceIds;
	current: boolean;
	strokeToken?: string;
	sent?: boolean;
	flowLabel?: string;
}>;
export type DiagramProof = Readonly<{
	kind: "graph" | "sequence";
	source: string;
	elements: readonly ProofElement[];
	visibleEvents: number;
	totalEvents: number;
	start: number;
	diagnostics: readonly string[];
}>;

export function property(item: ViewItem, key: string): unknown {
	return item.data && typeof item.data === "object" && !Array.isArray(item.data)
		? item.data[key] : undefined;
}

// Separate grammar contexts share numeric entity escaping, not JSON quoting.
// Never emit a label as syntax, a directive, HTML, a URL, or a CSS declaration.
export function label(text: string): string {
	return [...text].slice(0, 80).map(char => /[\p{L}\p{N} _.-]/u.test(char)
		? char : /\s/u.test(char) ? " " : "#" + char.codePointAt(0) + ";").join("");
}

// Sequence's automatic word wrapping can split Mermaid's internal entity
// escapes. Wrap plain text first, then escape it. Only this fixed line-break
// markup is generated by the trusted adapter, never supplied by the author.
function sequenceLabel(text: string): string {
	const words = [...text].slice(0, 80).join("").split(/\s+/).flatMap(word => {
		const characters = [...word], chunks: string[] = [];
		for (let start = 0; start < characters.length; start += 14) chunks.push(characters.slice(start, start + 14).join(""));
		return chunks;
	});
	const lines: string[] = [];
	let line = "";
	for (const word of words) {
		if (line && [...line + " " + word].length > 14) { lines.push(line); line = ""; }
		line += (line ? " " : "") + word;
	}
	if (line) lines.push(line);
	return lines.map(label).join("<br/>");
}

function element(item: ViewItem, index = 0): ProofElement {
	if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(item.id))
		throw new Error("Unsupported generated view identity");
	return Object.freeze({
		id: "thl_" + item.id, itemId: item.id, role: item.role,
		label: item.label, description: item.description, source: item.source,
		current: property(item, "current") === true || Number(property(item, "sentCurrent")) > 0,
		...(item.role === "relation" ? { strokeToken: "#" + (0x100000 + index).toString(16) } : {}),
		...(item.role === "event" ? { sent: property(item, "phase") === "sent" } : {}),
	});
}

function result(kind: DiagramProof["kind"], lines: string[], elements: ProofElement[],
	visibleEvents = 0, totalEvents = 0, start = 0, diagnostics: string[] = []): DiagramProof {
	return Object.freeze({ kind, source: lines.join("\n"), elements: Object.freeze(elements),
		visibleEvents, totalEvents, start, diagnostics: Object.freeze(diagnostics) });
}

export function graphProof(trace: CompiledTrace, view: ViewDescriptor,
	direction: "LR" | "TB" = "LR"): DiagramProof {
	if (view.kind !== "graph") throw new Error("Graph descriptor required");
	const visible = view.items.filter(item => ["entity", "group", "relation"].includes(item.role));
	if (visible.length > 1_400) throw new Error("Graph proof work limit exceeded");
	const elements = visible.map(element);
	const byItem = new Map(elements.map(item => [item.itemId, item]));
	const groups = visible.filter(item => item.role === "group");
	const groupBySource = new Map(groups.map(item => [item.source.groupIds![0], item]));
	const sourceGroups = new Map(trace.artifact.groups?.map(group => [group.id, group]));
	const entities = new Map(trace.artifact.entities.map(entity => [entity.id, entity]));
	const relations = new Map(trace.artifact.relations.map(relation => [relation.id, relation]));
	const lines = ["flowchart " + direction];
	const children = new Map<string | undefined, ViewItem[]>();
	for (const item of visible) {
		if (item.role === "relation") continue;
		const sourceGroup = item.role === "group"
			? sourceGroups.get(item.source.groupIds![0])?.parentId
			: entities.get(item.source.entityIds![0])?.groupId;
		const parent = sourceGroup ? groupBySource.get(sourceGroup)?.id : undefined;
		const list = children.get(parent) ?? [];
		list.push(item); children.set(parent, list);
	}
	function emit(parent?: string): void {
		for (const item of children.get(parent) ?? []) {
			const entry = byItem.get(item.id)!;
			if (item.role === "group" && property(item, "collapsed") !== true) {
				lines.push('subgraph ' + entry.id + '["' + label(item.label) + '"]');
				emit(item.id);
				lines.push("end");
			} else {
				lines.push(entry.id + '["' + label(item.label) + '"]');
				// A host-owned class is an explicit map key, not Mermaid's private ID.
				lines.push("class " + entry.id + " " + entry.id + "_source");
			}
		}
	}
	emit();
	for (const item of visible.filter(item => item.role === "relation")) {
		const entry = byItem.get(item.id)!;
		const from = byItem.get(item.fromItemId ?? ""), to = byItem.get(item.toItemId ?? "");
		if (!from || !to) throw new Error("Relation endpoint missing from projected graph");
		const description = item.source.relationIds?.length === 1
			? relations.get(item.source.relationIds[0])?.label : item.label;
		lines.push(from.id + " " + entry.id + "@-->" +
			(description ? '|"' + label(description) + '"|' : "") + " " + to.id);
		lines.push("class " + entry.id + " " + entry.id + "_source");
		// A unique trusted paint token survives documented classDef compilation.
		// The renderer binds it to this source entry without private SVG IDs.
		// No frame-dependent styling enters geometry source.
		lines.push("classDef " + entry.id + "_source stroke:" + entry.strokeToken + ",stroke-width:1.5px");
	}
	return result("graph", lines, elements);
}

export function sequenceProof(trace: CompiledTrace, view: ViewDescriptor,
	requestedStart?: number, windowSize = 40): DiagramProof {
	if (view.kind !== "sequence") throw new Error("Sequence descriptor required");
	if (!Number.isSafeInteger(windowSize) || windowSize < 1 || windowSize > 120)
		throw new Error("Sequence window must contain 1–120 events");
	const relations = new Map(trace.artifact.relations.map(relation => [relation.id, relation]));
	const actors = new Set<string>();
	// Reserve the complete modeled message participant set from frame zero.
	for (const step of trace.artifact.steps) for (const event of step.events) {
		if (event.type !== "message") continue;
		const relation = relations.get(event.relationId)!;
		actors.add(relation.from); actors.add(relation.to);
	}
	const lines = ["sequenceDiagram"];
	const actorIds = new Map<string, string>();
	const elements: ProofElement[] = [];
	for (const [index, entity] of trace.artifact.entities.entries()) {
		if (!actors.has(entity.id)) continue;
		const id = "thl_node_" + index;
		actorIds.set(entity.id, id);
		lines.push("participant " + id + " as " + sequenceLabel(entity.label));
		elements.push(Object.freeze({ id, itemId: "node_" + index, role: "entity",
			label: entity.label, description: "Modeled message participant, not evidence of current presence.",
			source: Object.freeze({ entityIds: Object.freeze([entity.id]) }), current: false }));
	}
	const events = view.items.filter(item => item.role === "event" && property(item, "type") === "message");
	const lastStart = Math.max(0, events.length - windowSize);
	const start = requestedStart === undefined ? lastStart : Math.min(lastStart,
		Math.max(0, Number.isSafeInteger(requestedStart) ? requestedStart : 0));
	const window = events.slice(start, start + windowSize);
	for (const item of window) {
		const entry = element(item);
		const from = actorIds.get(String(property(item, "fromEntityId")));
		const to = actorIds.get(String(property(item, "toEntityId")));
		if (!from || !to) throw new Error("Message endpoints missing from projected sequence");
		const phase = property(item, "phase");
		const relation = relations.get(item.source.relationIds![0])!;
		const flowLabel = (relation.label ? relation.label + " · " : "") + String(property(item, "messageId"));
		const caption = sequenceLabel(flowLabel + " · " + phase);
		if (phase === "sent") lines.push(from + "-)" + to + ": " + caption);
		else lines.push("Note over " + to + ": " + caption);
		elements.push(Object.freeze({ ...entry, flowLabel }));
	}
	return result("sequence", lines, elements, window.length, events.length, start,
		events.length > window.length ? ["Diagram window shows " + window.length + " of " +
			events.length + " recorded message phases. Use Earlier/Later event windows for all recorded phases."] : []);
}
